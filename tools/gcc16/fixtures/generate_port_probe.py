#!/usr/bin/env python3
"""Generate the assembly part of the integer-only CH32X035 hardware probe."""
from pathlib import Path

OUT = Path(__file__).parent / "PortProbe/probes.S"
REGS = {1: "ra", 2: "sp", 3: "gp", 4: "tp", 5: "t0", 6: "t1", 7: "t2",
        8: "s0", 9: "s1", **{10 + i: f"a{i}" for i in range(8)},
        **{18 + i: f"s{i + 2}" for i in range(10)}, 28: "t3", 29: "t4", 30: "t5", 31: "t6"}

lines = ["/* Generated by ../generate_port_probe.py; integer-only CH32X035. */", ".text"]
for scratch in ("t2", "t3"):
    name = "probe_regs_" + scratch
    lines += [f".global {name}", f".type {name},@function", name + ":", " addi sp,sp,-64", " sw ra,60(sp)"]
    lines += [f" sw s{i},{i * 4}(sp)" for i in range(12)]
    lines += [" la s11,register_probe", " sw zero,0(s11)", " sw sp,4(s11)",
              " sw gp,140(s11)", " sw tp,144(s11)"]
    lines += [f" li {reg},{0x100 + number}" for number, reg in REGS.items() if number not in (2, 3, 4, 27)]
    lines += [" la s11,register_probe", " li t0,0xe000e000", " li t1,0x4000",
              " sw t1,512(t0)", "1:", f" lw {scratch},0(s11)", f" beqz {scratch},1b", " sw sp,8(s11)"]
    lines += [f" sw {reg},{(number + 3) * 4}(s11)" for number, reg in REGS.items()]
    lines += [f" lw s{i},{i * 4}(sp)" for i in range(12)]
    lines += [" lw ra,60(sp)", " addi sp,sp,64", " ret", f".size {name},.-{name}"]

lines += [".global probe_xw", ".type probe_xw,@function", "probe_xw:",
          " addi sp,sp,-128", " addi a1,sp,64", " li a4,0"]
tests = 0
for kind in ("lbu", "sb", "lhu", "sh"):
    half = kind in ("lhu", "sh")
    load = kind in ("lbu", "lhu")
    for stack in (False, True):
        base = "sp" if stack else "a1"
        max_offset = (30 if half else 15) if stack else (62 if half else 31)
        op = "qk.c." + kind + ("sp" if stack else "")
        for offset in (0, max_offset):
            for value in ((0, 0x7fff, 0x8000, 0xffff) if half else (0, 0x7f, 0x80, 0xff)):
                lines += [f" li a2,{value}"]
                # Force the other operation to use its standard encoding, so
                # a matching pair of wrong XW encodings cannot mask a fault.
                plain_store = "sh" if half else "sb"
                plain_load = "lhu" if half else "lbu"
                if load:
                    lines += [" .option push", " .option norvc", f" {plain_store} a2,{offset}({base})",
                              " .option pop", f" {op} a3,{offset}({base})"]
                else:
                    lines += [f" {op} a2,{offset}({base})", " .option push", " .option norvc",
                              f" {plain_load} a3,{offset}({base})", " .option pop"]
                lines += [" beq a2,a3,2f", " addi a4,a4,1", "2:"]
                tests += 1
lines += [" mv a0,a4", " addi sp,sp,128", " ret", ".size probe_xw,.-probe_xw"]
OUT.write_text("\n".join(lines) + "\n")
print(f"Generated register-preservation probes and {tests} XW execution cases: {OUT}")
